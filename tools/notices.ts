/**
 * Generate THIRD_PARTY_NOTICES.md from the web app's production dependency
 * tree (§9.1), plus the models, which aren't npm packages.
 *
 *   node tools/notices.ts           write THIRD_PARTY_NOTICES.md
 *   node tools/notices.ts --check   fail if it is out of date (CI)
 */
import { execFileSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

interface Package {
	name: string;
	versions: string[];
	paths: string[];
	license: string;
	homepage?: string;
	author?: string;
}

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const target = path.join(root, 'THIRD_PARTY_NOTICES.md');
const LICENCE_FILE = /^(licen[cs]e|copying|notice)([.-].*)?$/i;

/** Licence texts in a package: top level, and one level down for bundled codecs (jSquash keeps them in codec/). */
function licenceTexts(dir: string): Array<{ file: string; text: string }> {
	const found: Array<{ file: string; text: string }> = [];
	const scan = (current: string, depth: number) => {
		for (const entry of readdirSync(current).sort()) {
			const full = path.join(current, entry);
			if (entry === 'node_modules') continue;
			const stat = statSync(full);
			if (stat.isDirectory() && depth < 1 && /^(codec|licenses?)$/i.test(entry)) scan(full, depth + 1);
			else if (stat.isFile() && LICENCE_FILE.test(entry)) {
				found.push({ file: path.relative(dir, full), text: readFileSync(full, 'utf8').trim() });
			}
		}
	};
	if (existsSync(dir)) scan(dir, 0);
	return found;
}

