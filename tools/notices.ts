export function render(packages: Package[]): string {
	const lines = [
		'# Third-party notices',
		'',
		'Hush is licensed under the Apache License 2.0. Its build output also contains',
		'the third-party components below, under their own licences.',
		'',
		'This file is generated by `node tools/notices.ts` from the web app’s',
		'production dependencies; CI fails if it is out of date. Do not edit by hand.',
		'',
		'## Models',
		'',
		'### NAFNet (SIDD), ONNX conversions',
		'',
		'- Source: https://github.com/megvii-research/NAFNet (weights: the official SIDD checkpoints)',
		'- Paper: Chen, Chu, Zhang, Sun, “Simple Baselines for Image Restoration”, ECCV 2022',
		'- Training data: Smartphone Image Denoising Dataset (SIDD), MIT License — https://abdokamel.github.io/sidd/',
		'- Hush ships ONNX conversions of the PyTorch checkpoints (fp32, fp16 and int8 variants).',
		'',
		'```',
		NAFNET_MIT,
		'```',
		'',
		'## Packages',
		'',
		'| Package | Version | Licence |',
		'| --- | --- | --- |',
		...packages.map(
			(p) => `| ${p.homepage ? `[${p.name}](${p.homepage})` : p.name} | ${p.versions.join(', ')} | ${p.license} |`,
		),
		'',
	];
	for (const p of packages) {
		lines.push(`### ${p.name} ${p.versions.join(', ')}`, '', `Licence: ${p.license}`, '');
		const texts = licenceTexts(p.paths[0] ?? '');
		if (texts.length === 0) lines.push('_No licence file in the package; see its repository._', '');
		for (const { file, text } of texts) lines.push(`\`${file}\`:`, '', '```', text, '```', '');
	}
	return lines.join('\n');
}

function main(): void {
	const json = execFileSync('pnpm', ['licenses', 'list', '--prod', '--json', '--filter', '@hush/web'], {
		cwd: root,
		encoding: 'utf8',
		maxBuffer: 64 * 1024 * 1024,
	});
	const byLicence = JSON.parse(json) as Record<string, Package[]>;
	const packages = Object.values(byLicence)
		.flat()
		// Workspace packages are Hush itself; type declarations never reach the browser.
		.filter((p) => !p.name.startsWith('@hush/') && !p.name.startsWith('@types/'))
		.sort((a, b) => a.name.localeCompare(b.name));

	const text = render(packages);
	if (process.argv.includes('--check')) {
		const current = existsSync(target) ? readFileSync(target, 'utf8') : '';
		if (current !== text) {
			console.error('THIRD_PARTY_NOTICES.md is out of date. Run `node tools/notices.ts` and commit the result.');
			process.exit(1);
		}
		console.log(`THIRD_PARTY_NOTICES.md is up to date (${packages.length} packages).`);
		return;
	}
	writeFileSync(target, text);
	console.log(`Wrote THIRD_PARTY_NOTICES.md (${packages.length} packages).`);
}

if (import.meta.main) main();
